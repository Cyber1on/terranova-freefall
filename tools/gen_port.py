"""Generate the glue of the standalone (port) build from symbols/*.csv.

usage: python3 tools/gen_port.py OUTDIR [--prefix _] [--port-dir port]

Writes into OUTDIR:
  tn_image.S     the original program's two memory objects as zero-filled arrays (tn_code_obj,
                 tn_data_obj) and every `data` row of the symbol tables as a symbol inside them, so
                 the decompiled C sees the game's globals with exactly the original layout.  The
                 arrays are filled at start-up from the player's own __FF.EXE (port/core/image.c); the
                 repository holds no game data.
  tn_funcmap.c   original address -> function, for every decompiled function and every original
                 routine the port stubs or takes from the C library (used to translate the code
                 pointers held in the original data, and by the 3D register-call glue).
  tn_stubs.c     an empty stand-in for every original routine that is still missing in the
                 port (third-party libraries, DOS and hardware code): it reports the first call
                 and returns 0.  A routine implemented by hand anywhere under port/ is skipped.

--prefix is the C symbol prefix of the target ("_" for 32-bit Windows, "" for ELF).
"""
import csv, glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

# Layout of __FF.EXE v1.09 (objects 1 and 3 of the LE image; object 2 is a 0x1BB-byte stub)
CODE_BASE, CODE_SIZE = 0x244000, 0x110940
DATA_BASE, DATA_SIZE = 0x355000, 0x10F900

# Original routines of the Watcom C library that the port takes from the host C library.
LIBC = set('''access atoi chdir chsize close eof exit fclose fgetc filelength fopen fputc free
fwrite getch getcwd getenv lseek malloc memmove memset mkdir open opendir printf puts rand read
remove rename stat strcmp strcmpi strncmp strncpy strnicmp strpbrk system tell tolower toupper
write'''.split())


def load_rows():
    rows = []
    # port/symbols-port.csv: original routines only the standalone build needs to name (the
    # verification build's thunks come from symbols/ alone, so it stays byte-identical)
    files = sorted(glob.glob(os.path.join(ROOT, 'symbols', 'symbols*.csv')))
    files.append(os.path.join(ROOT, 'port', 'symbols-port.csv'))
    for f in files:
        rows += list(csv.DictReader(open(f)))
    best = {}
    for r in rows:      # a name may be listed twice ('orig' in one file, 'decomp' in another)
        if r['name'] not in best or r['status'] == 'decomp':
            best[r['name']] = r
    return list(best.values())


def hand_written(port_dir):
    """Names of functions defined by hand in the port sources (these get no stub)."""
    names = set()
    # a definition: "type name(params)" at the start of a line, then "{" or the end of the line
    pat = re.compile(r'^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\([^;{]*\)\s*(\{.*)?$', re.M)
    for dp, _, fs in os.walk(port_dir):
        for f in fs:
            if f.endswith('.c'):
                src = open(os.path.join(dp, f), encoding='utf-8', errors='replace').read()
                for m in pat.finditer(src):
                    names.add(m.group(1))
    return names


def main():
    args = sys.argv[1:]
    out = args[0]
    prefix = args[args.index('--prefix') + 1] if '--prefix' in args else ''
    port_dir = args[args.index('--port-dir') + 1] if '--port-dir' in args else os.path.join(ROOT, 'port')
    os.makedirs(out, exist_ok=True)
    rows = load_rows()
    done = hand_written(port_dir)

    # ---- tn_image.S
    S = ['/* generated by tools/gen_port.py from symbols/*.csv: do not edit */\n',
         '' if prefix else '\t.section .note.GNU-stack,"",@progbits\n',
         '\t.bss\n\t.balign 4096\n',
         f'\t.globl {prefix}tn_code_obj\n{prefix}tn_code_obj:\n\t.space {CODE_SIZE:#x}\n',
         '\t.balign 4096\n',
         f'\t.globl {prefix}tn_data_obj\n{prefix}tn_data_obj:\n\t.space {DATA_SIZE:#x}\n']
    ndata = 0
    for r in sorted(rows, key=lambda r: int(r['address'], 16)):
        if r['kind'] != 'data':
            continue
        a = int(r['address'], 16)
        if CODE_BASE <= a < CODE_BASE + CODE_SIZE:
            base, off = 'tn_code_obj', a - CODE_BASE
        elif DATA_BASE <= a < DATA_BASE + DATA_SIZE:
            base, off = 'tn_data_obj', a - DATA_BASE
        else:
            sys.exit(f"data row {r['name']} at {a:#x} is outside the program's objects")
        S.append(f"\t.globl {prefix}{r['name']}\n\t.set {prefix}{r['name']}, {prefix}{base} + {off:#x}\n")
        ndata += 1
    open(os.path.join(out, 'tn_image.S'), 'w').write(''.join(S))

    # ---- tn_funcmap.c and tn_stubs.c
    funcs = sorted((r for r in rows if r['kind'] == 'func'), key=lambda r: int(r['address'], 16))
    stubs = [r for r in funcs if r['status'] != 'decomp' and r['name'] not in LIBC
             and r['name'] not in done]
    M = ['/* generated by tools/gen_port.py from symbols/*.csv: do not edit */\n',
         '#include "port.h"\n\n']
    for r in funcs:
        M.append(f"extern char {r['name']}[];\n")
    M.append('\nconst port_func port_funcs[] = {\n')
    seen = set()
    for r in funcs:
        a = int(r['address'], 16)
        if a in seen:            # two names for one address: keep the first
            continue
        seen.add(a)
        M.append(f"    {{ {a:#x}, {r['name']}, \"{r['name']}\" }},\n")
    M.append('};\nconst int port_nfuncs = sizeof port_funcs / sizeof port_funcs[0];\n')
    open(os.path.join(out, 'tn_funcmap.c'), 'w').write(''.join(M))

    T = ['/* generated by tools/gen_port.py from symbols/*.csv: do not edit.\n',
         ' * Stand-ins for original routines the port does not have yet (third-party\n',
         ' * libraries, DOS and hardware code).  Each reports its first call and returns 0. */\n',
         '#include "port.h"\n\n']
    for r in stubs:
        a = int(r['address'], 16)
        T.append(f"long {r['name']}() {{ static int n; if (!n++) port_stub_hit(\"{r['name']}\", {a:#x}, \"{r['library']}\"); return 0; }}\n")
    open(os.path.join(out, 'tn_stubs.c'), 'w').write(''.join(T))
    print(f'gen_port: {ndata} data symbols, {len(seen)} mapped functions, {len(stubs)} stubs')


if __name__ == '__main__':
    main()
