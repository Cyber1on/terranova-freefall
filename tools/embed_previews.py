"""embed_previews.py OUTDIR [--prefix _] PICTURE ... -- builds the options screen's preview
pictures (dist/Previews, port/ui/options.c) into tnfree: OUTDIR/previews.S takes each file in as
it is (.incbin), OUTDIR/previews.c lists them by name (the file name without .jpg / .png):
    const PortPreview port_previews[]; const int port_npreviews;
--prefix is the C symbol prefix of the target ("_" for 32-bit Windows, "" for ELF)."""
import os
import sys

args = sys.argv[1:]
out = args.pop(0)
prefix = ""
if args and args[0] == "--prefix":
    prefix = args[1]
    args = args[2:]
pics = sorted(args, key=lambda p: os.path.basename(p).lower())

S = ["/* generated by tools/embed_previews.py */\n"]
S.append('\t.section .rdata,"dr"\n' if prefix else "\t.section .rodata\n")
C = ["/* generated by tools/embed_previews.py */\n",
     "typedef struct { const char *name; const unsigned char *data; unsigned len; } PortPreview;\n"]
rows = []
for i, path in enumerate(pics):
    name = os.path.splitext(os.path.basename(path))[0]
    sym = "port_preview_%d" % i
    S.append("\t.globl %s%s\n%s%s:\n\t.incbin \"%s\"\n" %
             (prefix, sym, prefix, sym, os.path.abspath(path).replace("\\", "/")))
    C.append("extern const unsigned char %s[];\n" % sym)
    rows.append('    { "%s", %s, %d },\n' % (name, sym, os.path.getsize(path)))
if not prefix:
    S.append('\t.section .note.GNU-stack,"",@progbits\n')
C.append("const PortPreview port_previews[] = {\n")
C += rows or ['    { "", 0, 0 },\n']
C.append("};\nconst int port_npreviews = %d;\n" % len(rows))
with open(os.path.join(out, "previews.S"), "w") as f:
    f.write("".join(S))
with open(os.path.join(out, "previews.c"), "w") as f:
    f.write("".join(C))
