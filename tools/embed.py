"""embed.py OUT.c NAME=FILE ... -- writes each file as a C array (const unsigned char NAME[],
const unsigned NAME_len), for data built into tnfree (the help screen's fonts, port/ui/help.c)."""
import sys

out = sys.argv[1]
with open(out, "w") as f:
    f.write("/* generated by tools/embed.py */\n")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        f.write("const unsigned %s_len = %d;\n" % (name, len(data)))
        f.write("const unsigned char %s[%d] = {\n" % (name, len(data) + 1))
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("0};\n")
